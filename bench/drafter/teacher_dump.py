#!/usr/bin/env python3
"""Teacher dump for the drafter retrain (DRAFTER_RETRAIN §3): training rows from the served target.

A row is one token position: its input id and the drafter features the target computes there (the residual stream
after each of the drafter's target layers, config order, bf16, 5 x 5,120 for the DFlash2 drafter). The engine writes
them during a teacher-forced prefill (RAGON_DUMP_FEATURES, engine.cpp chunk_end; ragon-force `dump` drives it), so
the features are the served engine's own, bit for bit what the drafter sees in production. `convert` turns the raw
dump into SpecForge's offline records (one .ckpt per training sample: input_ids, loss_mask, hidden_states).

Subcommands (stdlib only except `convert`, which needs torch):
  sessions  agent-session rollouts (codex rollout-*.jsonl, generated by the served target) -> cases.jsonl. Each
            compaction segment of a session becomes one case: its last request's input plus that request's recorded
            output, rendered exactly as ragon-serve renders it (ragon-template --responses); the loss mask covers
            the assistant turns (after "<|im_start|>assistant\\n", through "<|im_end|>"). --holdout drops sessions
            whose SWE-bench instance id is listed (the replay set and the agreement gate stay unseen).
  public    a public prompt corpus (JSONL, --field) -> cases.jsonl: each prompt is rendered as a one-turn chat
            request, the served target answers it (POST /v1/completions on a ragon-serve, sampled), the answer is
            tokenized (ragon-force tokenize, CPU) and supervised.
  dump      cases.jsonl -> RAW (the engine's feature records) + dump.jsonl (per case: tokens, prefill ms).
  convert   RAW + cases.jsonl -> SpecForge offline records under OUT/rows_{g}-{g+N}/data_{i}.ckpt. A case longer
            than --max-length is cut into windows that overlap by --overlap tokens; the overlap's loss mask is zeroed,
            so every supervised token keeps at least --overlap tokens of context (its features already saw the whole
            prefix). Windows without two consecutive supervised tokens are skipped, as SpecForge's reader does.
  stats     cases.jsonl -> tokens, supervised tokens, distinct tasks, raw bytes.

Raw record (engine.cpp): int32 [magic 0x54414546, pos0, n, nfeat, hidden], int32 ids[n], bf16 rows[n][nfeat*hidden].
"""
import argparse
import json
import os
import re
import struct
import subprocess
import sys
import time
import urllib.request

MAGIC = 0x54414546
IM_START, IM_END = "<|im_start|>", "<|im_end|>"
TASK_RE = re.compile(r"/([A-Za-z0-9_.-]+__[A-Za-z0-9_.-]+-\d+)/")


def task_of(path):
    m = TASK_RE.search(path)
    return m.group(1) if m else os.path.basename(path)


def vocab_ids(tokenizer_json, *pieces):
    tok = json.load(open(tokenizer_json))
    added = {t["content"]: t["id"] for t in tok.get("added_tokens", [])}
    vocab = tok["model"]["vocab"]
    return [added[p] if p in added else vocab[p] for p in pieces]


def render(template_bin, tokenizer_json, bodies):
    """Responses bodies -> [{"ids", "text"}] as ragon-serve renders them."""
    inp = "".join(json.dumps({"body": b}) + "\n" for b in bodies)
    out = subprocess.run([template_bin, "--responses", tokenizer_json], input=inp, capture_output=True, text=True,
                         check=True).stdout.splitlines()
    assert len(out) == len(bodies), (len(out), len(bodies))
    return [json.loads(x) for x in out]


def assistant_spans(ids, im_start, im_end, assistant, newline):
    """[start, end) spans of assistant turns: after '<|im_start|>assistant\\n' through '<|im_end|>'."""
    spans, i, n = [], 0, len(ids)
    while i < n - 2:
        if ids[i] == im_start and ids[i + 1] == assistant and ids[i + 2] == newline:
            s = i + 3
            e = s
            while e < n and ids[e] != im_end:
                e += 1
            if e < n:
                spans.append([s, e + 1])
            i = e
        i += 1
    return spans


def cmd_sessions(a):
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "replay"))
    import replay  # parse_rollout, clean_item, custom_tools
    tools_plain = replay.custom_tools(json.load(open(a.tools)), "keep")
    tools_index = replay.custom_tools(json.load(open(a.tools_index)), "keep") if a.tools_index else tools_plain
    hold = set()
    for f in a.holdout or []:
        hold |= {ln.strip() for ln in open(f) if ln.strip()}
    im_start, im_end, assistant, newline = vocab_ids(a.tokenizer, IM_START, IM_END, "assistant", "Ċ")
    paths = [ln.strip() for ln in open(a.rollouts) if ln.strip()]
    out = open(a.out, "w")
    kept = skipped = 0
    for p in paths:
        if task_of(p) in hold:
            skipped += 1
            continue
        instr, reqs = replay.parse_rollout(p)
        # A segment ends where the next request does not extend this one's input (a compaction) or at the end.
        ends = [i for i in range(len(reqs)) if i + 1 == len(reqs) or len(reqs[i + 1]["input"]) <
                len(reqs[i]["input"]) + len(reqs[i]["out_items"])]
        bodies = []
        for i in ends:
            items = [replay.clean_item(x) for x in reqs[i]["input"] + reqs[i]["out_items"]]
            bodies.append({"model": a.model, "instructions": instr, "input": items,
                           "tools": tools_plain if "index-off" in p else tools_index, "tool_choice": "auto",
                           "parallel_tool_calls": True, "reasoning": {"effort": "none", "summary": "auto"},
                           "store": False, "stream": True})
        if not bodies:
            continue
        for k, r in enumerate(render(a.template, a.tokenizer, bodies)):
            ids = r["ids"]
            last = max(i for i, t in enumerate(ids) if t == im_start)  # drop the trailing generation prompt
            ids = ids[:last]
            spans = assistant_spans(ids, im_start, im_end, assistant, newline)
            if len(ids) > a.max_tokens:
                continue
            out.write(json.dumps({"id": f"{os.path.basename(p)}#{k}", "task": task_of(p), "source": "sessions",
                                  "ids": ids, "spans": spans}) + "\n")
            kept += 1
    print(json.dumps({"cases": kept, "held_out_sessions": skipped}), file=sys.stderr)


def cmd_public(a):
    im_end, = vocab_ids(a.tokenizer, IM_END)
    rows = []
    with open(a.corpus) as f:
        for ln, line in enumerate(f):
            if ln < a.skip:
                continue
            if len(rows) >= a.n:
                break
            rows.append((ln, json.loads(line)[a.field]))
    bodies = [{"model": a.model, "input": [{"type": "message", "role": "user",
                                             "content": [{"type": "input_text", "text": t}]}],
               "reasoning": {"effort": a.effort}} for _, t in rows]
    prompts = render(a.template, a.tokenizer, bodies)
    texts = []
    t0 = time.time()
    gen = 0
    for (ln, _), pr in zip(rows, prompts):
        req = {"model": a.model, "prompt": pr["ids"], "max_tokens": a.max_tokens, "seed": 1 + ln}
        if a.temperature is not None:
            req["temperature"] = a.temperature
        r = urllib.request.Request(a.url.rstrip("/") + "/v1/completions", data=json.dumps(req).encode(),
                                   headers={"Content-Type": "application/json"})
        c = json.load(urllib.request.urlopen(r, timeout=3600))
        ch = c["choices"][0]
        texts.append((ch["text"], ch.get("finish_reason")))
        gen += int(c.get("usage", {}).get("completion_tokens", 0))
    gen_s = time.time() - t0
    tk = subprocess.run([a.force, "tokenize", a.model_dir], input="".join(json.dumps(t) + "\n" for t, _ in texts),
                        capture_output=True, text=True, check=True).stdout.splitlines()
    assert len(tk) == len(texts)
    with open(a.out, "w") as out:
        for (ln, _), pr, (text, fin), t in zip(rows, prompts, texts, tk):
            ans = json.loads(t)["ids"] + ([im_end] if fin == "stop" else [])
            ids = pr["ids"] + ans
            out.write(json.dumps({"id": f"{os.path.basename(a.corpus)}:{ln}", "task": f"public:{ln}",
                                  "source": "public", "ids": ids, "spans": [[len(pr["ids"]), len(ids)]],
                                  "finish": fin}) + "\n")
    print(json.dumps({"cases": len(rows), "generated_tokens": gen, "generate_s": round(gen_s, 1),
                      "generate_tok_s": round(gen / gen_s, 2) if gen_s else None}), file=sys.stderr)


def cmd_dump(a):
    env = dict(os.environ, RAGON_DUMP_FEATURES=a.raw, RAGON_FORCE_DRAFT=a.draft,
               RAGON_FORCE_MAX_CONTEXT=str(a.max_context))
    if os.path.exists(a.raw):
        sys.exit(f"{a.raw} exists; the engine appends, so start from an empty file")
    cases = [json.loads(x) for x in open(a.cases) if x.strip()]
    t0 = time.time()
    p = subprocess.run([a.force, "dump", a.model_dir], input="".join(json.dumps({"ids": c["ids"]}) + "\n"
                                                                     for c in cases),
                       capture_output=True, text=True, env=env)
    wall = time.time() - t0
    lines = [json.loads(x) for x in p.stdout.splitlines() if x.startswith("{")]
    if p.returncode or len(lines) != len(cases):
        sys.exit(f"ragon-force dump failed ({p.returncode}, {len(lines)}/{len(cases)} cases): {p.stderr[-2000:]}")
    with open(a.log, "w") as f:
        for c, r in zip(cases, lines):
            f.write(json.dumps({"id": c["id"], "n": r["n"], "ms": r["ms"]}) + "\n")
    toks = sum(r["n"] for r in lines)
    ms = sum(r["ms"] for r in lines)
    print(json.dumps({"cases": len(cases), "tokens": toks, "prefill_s": round(ms / 1e3, 1), "wall_s": round(wall, 1),
                      "prefill_tok_s": round(toks / (ms / 1e3), 1), "raw_bytes": os.path.getsize(a.raw),
                      "raw_bytes_per_row": round(os.path.getsize(a.raw) / toks, 1)}))


def read_raw(path):
    """Yields (pos0, ids, rows bytes, nfeat, hidden) per engine record."""
    with open(path, "rb") as f:
        while True:
            h = f.read(20)
            if not h:
                return
            magic, pos0, n, nfeat, hidden = struct.unpack("<5i", h)
            assert magic == MAGIC, f"bad magic at {f.tell() - 20}"
            ids = struct.unpack(f"<{n}i", f.read(4 * n))
            yield pos0, ids, f.read(2 * n * nfeat * hidden), nfeat, hidden


def cases_from_raw(path):
    """Groups the raw records into cases (a case starts at pos0 == 0) -> (ids, [row bytes chunks], width)."""
    cur = None
    for pos0, ids, rows, nfeat, hidden in read_raw(path):
        if pos0 == 0:
            if cur:
                yield cur
            cur = ([], [], nfeat * hidden)
        assert cur is not None and pos0 == len(cur[0]), f"non-contiguous record at pos0 {pos0}"
        cur[0].extend(ids)
        cur[1].append(rows)
    if cur:
        yield cur


def supervised_ok(mask):
    return any(mask[i] and mask[i + 1] for i in range(len(mask) - 1))


def cmd_convert(a):
    import torch
    cases = [json.loads(x) for x in open(a.cases) if x.strip()]
    idx = written = toks = 0
    nbytes = 0
    for case, (ids, chunks, width) in zip(cases, cases_from_raw(a.raw), strict=True):
        T = len(case["ids"])
        assert list(ids) == case["ids"], f"{case['id']}: dumped ids differ from the case ({len(ids)} vs {T})"
        feats = torch.frombuffer(bytearray(b"".join(chunks)), dtype=torch.bfloat16).view(T, width)
        mask = [0] * T
        for s, e in case["spans"]:
            mask[s:e] = [1] * (e - s)
        starts = [0] if T <= a.max_length else list(range(0, T - a.overlap, a.max_length - a.overlap))
        for s in starts:
            e = min(s + a.max_length, T)
            m = mask[s:e]
            if s:
                m[:a.overlap] = [0] * min(a.overlap, len(m))
            if not supervised_ok(m):
                continue
            rec = {"input_ids": torch.tensor(ids[s:e], dtype=torch.int64),
                   "loss_mask": torch.tensor(m, dtype=torch.int64),
                   "hidden_states": feats[s:e].clone().unsqueeze(0)}
            if torch.isnan(rec["hidden_states"]).any():
                print(f"skip {case['id']}[{s}:{e}]: NaN", file=sys.stderr)
                continue
            g = (idx // a.group) * a.group
            path = os.path.join(a.out, f"rows_{g}-{g + a.group}", f"data_{idx}.ckpt")
            os.makedirs(os.path.dirname(path), exist_ok=True)
            torch.save(rec, path)
            nbytes += os.path.getsize(path)
            toks += e - s
            idx += 1
            written += 1
    print(json.dumps({"records": written, "tokens": toks, "bytes": nbytes,
                      "bytes_per_row": round(nbytes / toks, 1) if toks else None}))


def cmd_stats(a):
    n = toks = sup = 0
    tasks = set()
    for line in open(a.cases):
        c = json.loads(line)
        n += 1
        toks += len(c["ids"])
        sup += sum(e - s for s, e in c["spans"])
        tasks.add(c["task"])
    print(json.dumps({"cases": n, "tasks": len(tasks), "tokens": toks, "supervised": sup,
                      "raw_bytes": toks * (4 + 2 * a.width)}))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sessions")
    s.add_argument("--rollouts", required=True, help="file listing rollout-*.jsonl paths")
    s.add_argument("--tools", required=True)
    s.add_argument("--tools-index")
    s.add_argument("--holdout", action="append", help="file of SWE-bench instance ids to leave out (repeatable)")
    s.add_argument("--tokenizer", required=True, help="the target's tokenizer.json")
    s.add_argument("--template", required=True, help="the ragon-template binary")
    s.add_argument("--model", default="RadixArk/Qwen3.8-27B-NVFP4")
    s.add_argument("--max-tokens", type=int, default=131072)
    s.add_argument("--out", required=True)
    p = sub.add_parser("public")
    p.add_argument("--corpus", required=True)
    p.add_argument("--field", default="problem")
    p.add_argument("--n", type=int, default=32)
    p.add_argument("--skip", type=int, default=0)
    p.add_argument("--url", required=True, help="a ragon-serve with the served target")
    p.add_argument("--tokenizer", required=True)
    p.add_argument("--template", required=True)
    p.add_argument("--force", required=True, help="the ragon-force binary (tokenize runs on the CPU)")
    p.add_argument("--model-dir", required=True)
    p.add_argument("--model", default="RadixArk/Qwen3.8-27B-NVFP4")
    p.add_argument("--effort", default="none")
    p.add_argument("--max-tokens", type=int, default=2048)
    p.add_argument("--temperature", type=float)
    p.add_argument("--out", required=True)
    d = sub.add_parser("dump")
    d.add_argument("--cases", required=True)
    d.add_argument("--force", required=True)
    d.add_argument("--model-dir", required=True)
    d.add_argument("--draft", required=True, help="a drafter dir: its config names the target layers")
    d.add_argument("--max-context", type=int, default=131072)
    d.add_argument("--raw", required=True)
    d.add_argument("--log", required=True)
    c = sub.add_parser("convert")
    c.add_argument("--cases", required=True)
    c.add_argument("--raw", required=True)
    c.add_argument("--out", required=True)
    c.add_argument("--max-length", type=int, default=8192)
    c.add_argument("--overlap", type=int, default=2048)
    c.add_argument("--group", type=int, default=2000)
    t = sub.add_parser("stats")
    t.add_argument("--cases", required=True)
    t.add_argument("--width", type=int, default=5 * 5120)
    a = ap.parse_args()
    {"sessions": cmd_sessions, "public": cmd_public, "dump": cmd_dump, "convert": cmd_convert,
     "stats": cmd_stats}[a.cmd](a)


if __name__ == "__main__":
    main()
